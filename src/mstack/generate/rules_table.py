import argparse
import datetime
import logging
import re
from collections import Counter
from pathlib import Path

from mstack.guards.check_exceptions import collect_exceptions, python_files
from mstack.guards.check_rule_coverage import (
    load_ast_grep_rules,
    load_import_linter_contracts,
    parse_checks_section,
)

logger = logging.getLogger(__name__)

START_MARKER = "<!-- rules-table:start -->"
END_MARKER = "<!-- rules-table:end -->"
MARKED_BLOCK = re.compile(
    re.escape(START_MARKER) + r".*?" + re.escape(END_MARKER), re.DOTALL
)


def build_table(rules_dir: Path, config: Path, importlinter: Path) -> str:
    ast_grep_rules = load_ast_grep_rules(config)
    contracts = load_import_linter_contracts(importlinter)
    exceptions, _ = collect_exceptions(python_files([]), datetime.date.today())
    active_exceptions = Counter(exception["rule"] for exception in exceptions)

    rows = [
        "| Rule | Check | Enforced by | Severity | Active exceptions |",
        "| --- | --- | --- | --- | --- |",
    ]
    for mdc_path in sorted(rules_dir.rglob("*.mdc")):
        section = parse_checks_section(mdc_path) or {
            "enforced_by": {},
            "llm_review": False,
        }
        rule = f"`{mdc_path.as_posix()}`"
        for check_id in sorted(section["enforced_by"]):
            if check_id in ast_grep_rules:
                tool, severity = "ast-grep", ast_grep_rules[check_id]["severity"]
            elif check_id in contracts:
                tool, severity = "import-linter", "error"
            else:
                tool, severity = "missing", "-"
            rows.append(
                f"| {rule} | `{check_id}` | {tool} | {severity} | {active_exceptions[check_id]} |"
            )
        if section["llm_review"]:
            rows.append(f"| {rule} | - | LLM review on the PR | comment only | - |")
        if not section["enforced_by"] and not section["llm_review"]:
            rows.append(f"| {rule} | - | **nothing (no Checks section)** | - | - |")
    return "\n".join(rows) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="mstack rules-table", description="Generate the rule -> check table."
    )
    parser.add_argument("--rules-dir", type=Path, default=Path(".cursor/rules"))
    parser.add_argument("--config", type=Path, default=Path("lint-rules/sgconfig.yml"))
    parser.add_argument("--importlinter", type=Path, default=Path(".importlinter"))
    parser.add_argument("--output", type=Path, default=Path("docs/rules-table.md"))
    arguments = parser.parse_args(argv)

    table = build_table(arguments.rules_dir, arguments.config, arguments.importlinter)
    arguments.output.write_text(
        "# Rules table\n\n"
        "Generated by `make rules-table` from `.cursor/rules/`, `lint-rules/` and `.importlinter`. "
        "Do not edit by hand.\n\n" + table,
        encoding="utf-8",
    )
    logger.info("rules_table: wrote %s", arguments.output)
    for agent_file in (Path("CLAUDE.md"), Path("AGENTS.md")):
        if not agent_file.is_file():
            continue
        content = agent_file.read_text(encoding="utf-8")
        if START_MARKER not in content or END_MARKER not in content:
            continue
        updated = MARKED_BLOCK.sub(
            lambda _match: f"{START_MARKER}\n{table}{END_MARKER}", content, count=1
        )
        if updated != content:
            agent_file.write_text(updated, encoding="utf-8")
            logger.info("rules_table: updated the table in %s", agent_file)
    return 0
